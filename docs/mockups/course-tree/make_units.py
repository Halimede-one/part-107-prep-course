"""Write units.js for the course-tree mockup from curriculum/regulations/objectives.md.

Run from the repo root:  python3 docs/mockups/course-tree/make_units.py

The mockup needs each unit's title, which /api/state does not carry yet. The
real shell would get the title from the server; this keeps the mockup honest
to the actual unit list and order.
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OBJECTIVES = os.path.join(ROOT, "curriculum", "regulations", "objectives.md")
CURRICULUM = os.path.join(ROOT, "curriculum", "regulations")
OUT = os.path.join(HERE, "units.js")

_TASK = re.compile(r"^## Task ([A-F])\. (.+)$")
_UNIT = re.compile(r"^\|\s*(UA\.I\.([A-F])\.K(\d+)([a-d]?))\s*\|\s*(.+?)\s*\|\s*$")


def main():
    tasks, units = {}, []
    with open(OBJECTIVES, encoding="utf-8") as handle:
        for line in handle:
            task = _TASK.match(line.strip())
            if task:
                tasks[task.group(1)] = task.group(2).strip()
                continue
            unit = _UNIT.match(line)
            if not unit:
                continue
            code, task_letter, _number, sub, title = unit.groups()
            title = re.sub(r"^[a-d]\.\s*", "", title).rstrip(".")
            gears = [1, 2]
            if os.path.isfile(os.path.join(CURRICULUM, "%s.gear3.md" % code)):
                gears.append(3)
            units.append({"id": code, "task": task_letter, "title": title,
                          "sub": bool(sub), "available_gears": gears,
                          "written": os.path.isfile(os.path.join(CURRICULUM, "%s.md" % code))})
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("// Generated by make_units.py from curriculum/regulations/objectives.md. Do not edit.\n")
        handle.write("window.COURSE_TASKS = %s;\n" % json.dumps(tasks, indent=1))
        handle.write("window.COURSE_UNITS = %s;\n" % json.dumps(units, indent=1))
    print("%d units, %d with gear 3 -> %s" % (
        len(units), sum(1 for u in units if 3 in u["available_gears"]), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
